import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { buildDemoState } from '../../src/demo';
import { score } from '../../src/game/engine';
import { BALLOONS, ROUNDS, SCORING, TRACK_LENGTH, WIND_CARDS, balloonName } from '../../src/game/data';

const state = buildDemoState('end', 'en');
const finalScores = score(state);
const data = {
  source: 'Generated by video/scripts/gen-data.ts from the pure engine demo state.',
  seed: state.config.seed,
  players: state.config.seats.map((seat) => seat.name),
  trackLength: TRACK_LENGTH,
  rounds: state.history.map((round) => ({
    round: round.round,
    supports: round.supports,
    tailwinds: round.tailwinds,
    wind: round.wind,
    positionsBefore: round.positionsBefore,
    positionsAfter: round.positionsAfter,
    leaders: round.leaders,
    seconds: round.seconds,
    points: round.points,
    overallLeaders: round.overallLeaders,
    overallPoints: round.overallPoints,
  })),
  finalPositions: state.positions,
  overallLeaders: state.overallLeaders,
  scores: finalScores,
  winner: finalScores.filter((row) => row.rank === 1).map((row) => row.name),
  facts: {
    rounds: ROUNDS,
    trackLength: TRACK_LENGTH,
    balloons: BALLOONS.length,
    windCards: WIND_CARDS,
    scoring: SCORING,
    players: state.config.playerCount,
  },
  balloons: BALLOONS.map((balloon, index) => ({
    id: balloon.id,
    en: balloonName(balloon, 'en'),
    zh: balloonName(balloon, 'zh'),
    color: balloon.color,
    light: balloon.light,
    pattern: balloon.pattern,
    finalPosition: state.positions[index],
  })),
};

const out = path.resolve(import.meta.dirname, '..', 'src', 'data');
mkdirSync(out, { recursive: true });
writeFileSync(path.join(out, 'game.json'), `${JSON.stringify(data, null, 2)}\n`);
console.log(
  `game.json: ${state.config.seed}, winner ${data.winner.join(' + ')}, rounds ${data.rounds.length}, track ${TRACK_LENGTH}`,
);
