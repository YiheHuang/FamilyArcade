import { mkdirSync, writeFileSync } from 'node:fs';
import { apply, rngForConfig, setup, view } from '../src/game/engine';
import { mulberry32 } from '../src/game/rng';
import { chooseMove } from '../src/ai/ai';
import type { AiLevel, GameConfig, GameState } from '../src/game/types';

const GAMES = 200;
const BUDGET_MS = 40;
const PAIRINGS: [AiLevel, AiLevel][] = [
  ['companion', 'easy'],
  ['easy', 'normal'],
  ['normal', 'hard'],
];

interface Result {
  strongWins: number;
  weakWins: number;
  draws: number;
  turns: number;
  moves: number;
  ms: number;
}

function play(strong: AiLevel, weak: AiLevel, game: number): Omit<Result, 'strongWins' | 'weakWins' | 'draws'> & {
  winner: 'strong' | 'weak' | 'draw';
} {
  const strongSeat = game % 2;
  const weakSeat = 1 - strongSeat;
  const cfg: GameConfig = {
    playerCount: 2,
    seats: [
      { name: 'A', kind: 'ai', level: strongSeat === 0 ? strong : weak },
      { name: 'B', kind: 'ai', level: strongSeat === 1 ? strong : weak },
    ],
    seed: `cal-${strong}-${weak}-${game}`,
  };
  let state: GameState = setup(cfg, rngForConfig(cfg));
  let guard = 0;
  let ms = 0;
  let moves = 0;
  while (state.status === 'playing' && guard++ < 500) {
    const seat = state.current;
    const level = cfg.seats[seat].level;
    const start = performance.now();
    const move = chooseMove(
      view(state, seat),
      level,
      BUDGET_MS,
      mulberry32(game * 1000 + guard),
    );
    ms += performance.now() - start;
    if (!move) break;
    const out = apply(state, move);
    if (!out.ok) throw new Error(`${out.reason} in calibration`);
    state = out.state;
    moves++;
  }
  const winnerSeat = state.winners.length === 1 ? state.winners[0] : null;
  return {
    winner: winnerSeat === null ? 'draw' : winnerSeat === strongSeat ? 'strong' : 'weak',
    turns: state.turn,
    moves,
    ms,
  };
}

const rows: {
  pairing: string;
  strongWins: number;
  weakWins: number;
  draws: number;
  rate: number;
  avgTurns: number;
  avgMs: number;
}[] = [];

for (const [strong, weak] of PAIRINGS) {
  const result: Result = { strongWins: 0, weakWins: 0, draws: 0, turns: 0, moves: 0, ms: 0 };
  for (let game = 0; game < GAMES; game++) {
    const one = play(strong, weak, game);
    if (one.winner === 'strong') result.strongWins++;
    else if (one.winner === 'weak') result.weakWins++;
    else result.draws++;
    result.turns += one.turns;
    result.moves += one.moves;
    result.ms += one.ms;
    process.stdout.write('.');
  }
  process.stdout.write('\n');
  rows.push({
    pairing: `${strong} vs ${weak}`,
    strongWins: result.strongWins,
    weakWins: result.weakWins,
    draws: result.draws,
    rate: result.strongWins / GAMES,
    avgTurns: result.turns / GAMES,
    avgMs: result.ms / Math.max(1, result.moves),
  });
}

const lines = [
  '# AI calibration (200-game smoke)',
  '',
  `Generated by \`scripts/ai-calibration.ts\` on ${new Date().toISOString().slice(0, 10)}.`,
  `This is a **${GAMES}-game sample per pairing** (${GAMES * 3} games total). It is a`,
  `smoke calibration for gross level inversions, not a polished published ladder.`,
  '',
  `- Budget: **${BUDGET_MS} ms** per move for every level (faster than production Hard).`,
  `- Seats alternate each game; the first level in the pairing is “strong”.`,
  `- All moves are applied by the real engine; shared first places count as draws.`,
  '',
  '| Pairing | Games | Strong wins | Weak wins | Draws | Strong win rate | Avg turns | Avg ms/move |',
  '| --- | --- | --- | --- | --- | --- | --- | --- |',
  ...rows.map(
    (r) =>
      `| ${r.pairing} | ${GAMES} | ${r.strongWins} | ${r.weakWins} | ${r.draws} | ${(r.rate * 100).toFixed(0)}% | ${r.avgTurns.toFixed(1)} | ${r.avgMs.toFixed(1)} |`,
  ),
  '',
  'Target from the family-game standard: Hard over Normal and Normal over Easy roughly',
  '60–70%; Easy over Companion 55–65%. Two targets are not met in this sample: Easy',
  'beats Companion about 72%, and Hard only reaches about 49% vs Normal. Normal over',
  'Easy is at the low end (60%). The likely causes are the shallow Companion policy and',
  "Hard's two-step plan over-weighting one future line; tuning and family playtests are",
  'the next step. Treat this table as honest directional evidence, not a release claim.',
  '',
].join('\n');
mkdirSync('docs', { recursive: true });
writeFileSync('docs/ai-calibration.md', lines, 'utf8');
console.log(lines);
