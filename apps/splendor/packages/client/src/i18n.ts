const DICTS: Record<Lang, Dict> = { zh, en };

let current: Lang = 'en';

export function setLang(l: Lang): void {
  current = l;
}

export function getLang(): Lang {
  return current;
}

/** 当前语言的文案表（Proxy：语言切换后重新读取即生效） */
export const T: Dict = new Proxy({} as Dict, {
  get: (_target, key: string) => DICTS[current][key as keyof Dict],
});

/** AI 档位标签 / 说明（随语言） */
export const AI_LABEL = new Proxy({} as Record<AiLevel, string>, {
  get: (_t, key: string) => DICTS[current].aiLabel[key as AiLevel],
});

export const AI_DESC = new Proxy({} as Record<AiLevel, string>, {
  get: (_t, key: string) => DICTS[current].aiDesc[key as AiLevel],
});

/** 错误码 → 本地化文案（未知码原样返回，便于排查）；参数若是宝石色会一并本地化 */
export function errText(code: string): string {
  const raw = code ?? '';
  const [key, param] = raw.split(':');
  const dict = DICTS[current];
  const table = dict.errors as Record<string, string>;
  const tpl = table[key!];
  if (!tpl) return raw;
  if (param == null) return tpl;
  const gemKey = `${param}`.trim().toLowerCase();
  const named = dict.gems.short[gemKey];
  return tpl.replace('{n}', named ?? param);
}
