export function pieceName(
  lang: Lang,
  type: PieceType,
  promoted = false,
  full = false,
): string {
  if (lang === 'zh') return promoted ? PROMOTED_ZH[type] : PIECE_ZH[type];
  if (full && !promoted) return PIECE_EN_FULL[type];
  return promoted ? PROMOTED_EN[type] : PIECE_EN[type];
}

export function formatMove(move: Move, board: GameStateBoard, lang: Lang): string {
  if (move.kind === 'drop') {
    return `${pieceName(lang, move.type, false)}*${squareName(move.to)}`;
  }
  const moving = board[move.from];
  const type = moving?.type ?? move.piece;
  const promoted = Boolean(move.promote || moving?.promoted);
  const label = type ? pieceName(lang, type, promoted) : '?';
  return `${label} ${squareName(move.from)}-${squareName(move.to)}`;
}

type GameStateBoard = readonly ({ type: PieceType; promoted: boolean } | null)[];

