const DICT: Record<Lang, Record<Key, string>> = { en: EN, zh: ZH };

const VALUE_KEYS: readonly (readonly [Key, Key])[] = [
  ['light', 'dark'],
  ['round', 'square'],
  ['short', 'tall'],
  ['solid', 'hollow'],
];

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('familyarcade.lang');
    if (saved === 'en' || saved === 'zh') return saved;
  } catch {
    /* ignore */
  }
  if (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('zh')) return 'zh';
  return 'en';
}

export function t(lang: Lang, key: Key, params?: Record<string, string | number>): string {
  let text = DICT[lang][key] ?? EN[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function formatList(lang: Lang, items: string[]): string {
  if (items.length === 0) return '';
  if (items.length === 1) return items[0];
  if (lang === 'zh') return items.join('、');
  if (items.length === 2) return `${items[0]} and ${items[1]}`;
  return `${items.slice(0, -1).join(', ')}, and ${items[items.length - 1]}`;
}

export function attributeValueName(lang: Lang, attribute: number, value: 0 | 1): string {
  const pair = VALUE_KEYS[attribute] ?? VALUE_KEYS[0];
  return t(lang, pair[value]);
}

export function pieceDescription(lang: Lang, piece: number): string {
  const values = [0, 1, 2, 3].map((attribute) =>
    attributeValueName(lang, attribute, ((piece >> attribute) & 1) as 0 | 1),
  );
  return values.join(lang === 'zh' ? '、' : ', ');
}

export function pieceAriaLabel(lang: Lang, piece: number): string {
  return t(lang, 'pieceAria', { attrs: pieceDescription(lang, piece) });
}

export function attributesDescription(
  lang: Lang,
  attributes: { attribute: number; value: 0 | 1 }[],
): string {
  return formatList(
    lang,
    attributes.map((item) => attributeValueName(lang, item.attribute, item.value)),
  );
}

