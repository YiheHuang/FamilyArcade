const DICT: Record<Lang, Record<MessageKey, string>> = { en: EN, zh: ZH };

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('familyarcade.lang');
    if (saved === 'en' || saved === 'zh') return saved;
  } catch {
    /* ignore */
  }
  if (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('zh')) return 'zh';
  return 'en';
}

export function t(
  lang: Lang,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  let text = DICT[lang][key] ?? EN[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function playerName(lang: Lang, player: 'W' | 'B'): string {
  return t(lang, player === 'W' ? 'white' : 'black');
}

export function playerShort(lang: Lang, player: 'W' | 'B'): string {
  return t(lang, player === 'W' ? 'whiteShort' : 'blackShort');
}
