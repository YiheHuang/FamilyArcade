const DICT: Record<Lang, Record<MessageKey, string>> = { en: EN, zh: ZH };

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('familyarcade.lang');
    if (saved === 'en' || saved === 'zh') return saved;
  } catch {
    /* ignore */
  }
  if (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('zh')) {
    return 'zh';
  }
  return 'en';
}

export function t(
  lang: Lang,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  let text = DICT[lang][key] ?? EN[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

const WIND_KEYS = ['windEast', 'windSouth', 'windWest', 'windNorth'] as const;

export function windName(lang: Lang, wind: number): string {
  return t(lang, WIND_KEYS[Math.max(0, Math.min(3, wind - 1))]);
}

const POSITION_KEYS = ['seatSouth', 'seatEast', 'seatNorth', 'seatWest'] as const;

export function seatPositionName(lang: Lang, seat: number): string {
  return t(lang, POSITION_KEYS[Math.max(0, Math.min(3, seat))]);
}

const CN_NUMBERS = ['', '一', '二', '三', '四', '五', '六', '七', '八', '九'];

export function tileName(lang: Lang, tile: Tile): string {
  if (tile.suit === 'z') {
    if (tile.rank <= 4) return windName(lang, tile.rank);
    const dragonKeys = ['dragonRed', 'dragonGreen', 'dragonWhite'] as const;
    return t(lang, dragonKeys[Math.max(0, Math.min(2, tile.rank - 5))]);
  }
  if (lang === 'zh') {
    const suit = tile.suit === 'm' ? '万' : tile.suit === 'p' ? '筒' : '条';
    return `${CN_NUMBERS[tile.rank] ?? tile.rank}${suit}`;
  }
  const suit =
    tile.suit === 'm' ? t(lang, 'tileCharacter') : tile.suit === 'p' ? t(lang, 'tileDots') : t(lang, 'tileBamboo');
  return `${tile.rank} ${suit}`;
}

export function tileSuitChar(tile: Tile): string {
  if (tile.suit === 'm') return '萬';
  if (tile.suit === 'p') return '筒';
  if (tile.suit === 's') return '條';
  return '';
}

