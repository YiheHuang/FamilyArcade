const SUIT_NAME: Record<Suit, { en: string; zh: string }> = {
  S: { en: 'Spades', zh: '黑桃' },
  H: { en: 'Hearts', zh: '红桃' },
  D: { en: 'Diamonds', zh: '方块' },
  C: { en: 'Clubs', zh: '梅花' },
};

const RANK_NAME: Record<string, string> = {
  A: 'A',
  K: 'K',
  Q: 'Q',
  J: 'J',
  '10': '10',
};

export function cardName(lang: Lang, card: Card): string {
  const rank = RANK_NAME[card.rank] ?? card.rank;
  return lang === 'zh'
    ? `${SUIT_NAME[card.suit].zh} ${rank}`
    : `${rank} of ${SUIT_NAME[card.suit].en}`;
}
