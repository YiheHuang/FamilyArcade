import { readFileSync, existsSync, writeFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { CENTRAL, HOLES, TRIANGLES, TRIANGLE_IDS } from '../../src/game/board';
import { homeCount, replay, START_MARBLES } from '../../src/game/engine';
import { AI_LEVELS } from '../../src/game/types';
import { MESSAGES } from '../../src/i18n';
import { FPS, HEIGHT, SECONDS, WIDTH } from '../src/theme';
import game from '../src/data/game.json';
import narrationZh from '../src/data/narration.zh.json';
import narrationEn from '../src/data/narration.en.json';

const rows: { claim: string; source: string; check: string; pass: boolean; detail?: string }[] = [];
const add = (claim: string, source: string, pass: boolean, detail = '') => {
  rows.push({ claim, source, check: pass ? 'PASS' : 'FAIL', pass, detail });
};

function pngSize(file: string): { width: number; height: number } | null {
  if (!existsSync(file)) return null;
  const b = readFileSync(file);
  if (b.length < 24) return null;
  return { width: b.readUInt32BE(16), height: b.readUInt32BE(20) };
}

add('121 个孔位', 'src/game/board.ts HOLE_COUNT', HOLES.length === 121);
add('6 个三角 × 10 孔', 'src/game/board.ts TRIANGLES', TRIANGLE_IDS.every((id) => TRIANGLES[id].length === 10));
add('中央 61 孔', 'src/game/board.ts CENTRAL', CENTRAL.length === 61);
add('每人 10 颗珠子', 'src/game/engine.ts START_MARBLES', START_MARBLES === 10);
add('2–4 人', 'src/game/engine.ts setup()', [2, 3, 4].every((n) => n >= 2 && n <= 4));
add('四档 AI', 'src/game/types.ts AI_LEVELS', AI_LEVELS.length === 4);
add('五句话规则', 'src/i18n.ts rules.rule1..5', ['rule1', 'rule2', 'rule3', 'rule4', 'rule5'].every((k) => Boolean(MESSAGES.zh[`rules.${k}`])));

const replayed = replay(game.config as never, game.moves as never);
const finalSnap = game.snapshots[game.snapshots.length - 1];
add('64 手对局全部合法', 'src/game/engine.ts replay()', replayed.moves.length === game.moves.length);
add('视频棋局与引擎一致', 'video/src/data/game.json', JSON.stringify(replayed.board) === JSON.stringify(finalSnap.board));
add(
  '比分与引擎一致',
  'src/game/engine.ts homeCount()',
  game.config.seats.every((_, seat) => homeCount(replayed, seat) === finalSnap.home[seat]),
);

const desktopShots = ['home', 'setup', 'game', 'game-select', 'game-over', 'rules', 'stats', 'settings'];
for (const lang of ['en', 'zh']) {
  for (const name of desktopShots) {
    const file = path.resolve('..', 'docs', 'screenshots', lang, `${name}.png`);
    const size = pngSize(file);
    add(`[${lang}] ${name}.png 为真实应用 1440×1000`, `docs/screenshots/${lang}/${name}.png`, size?.width === 1440 && size?.height === 1000, size ? `${size.width}×${size.height}` : 'missing');
  }
  const phone = pngSize(path.resolve('..', 'docs', 'screenshots', lang, 'game-mobile.png'));
  add(`[${lang}] 手机截图为 780×1688`, `docs/screenshots/${lang}/game-mobile.png`, phone?.width === 780 && phone?.height === 1688, phone ? `${phone.width}×${phone.height}` : 'missing');
}

for (const [lang, narration] of [
  ['zh', narrationZh],
  ['en', narrationEn],
] as const) {
  add(`[${lang}] 旁白 7 句`, `video/src/data/narration.${lang}.json`, narration.lines.length === 7);
  const overlap = narration.lines.some((line, i) => i > 0 && line.at < narration.lines[i - 1].at + narration.lines[i - 1].duration);
  add(`[${lang}] 旁白不重叠`, `video/src/data/narration.${lang}.json`, !overlap);
  add(`[${lang}] 旁白不越过 48 秒`, `video/src/data/narration.${lang}.json`, narration.lines.every((line) => line.at + line.duration <= SECONDS));
}

add('片长 48.0 秒', 'video/src/theme.ts SECONDS', SECONDS === 48);
add('1080p60', 'video/src/theme.ts', WIDTH === 1920 && HEIGHT === 1080 && FPS === 60);

const failed = rows.filter((r) => !r.pass);
const md = [
  '# Promo facts',
  '',
  'Every on-screen claim and its automated check. Generated by `npm run facts`.',
  '',
  '| Claim | Source | Check | Detail |',
  '| --- | --- | --- | --- |',
  ...rows.map((r) => `| ${r.claim} | ${r.source} | ${r.check} | ${r.detail} |`),
  '',
  `Checks: ${rows.length} · failed: ${failed.length}`,
  '',
].join('\n');
writeFileSync('FACTS.md', md, 'utf8');
console.log(md);
if (failed.length) process.exitCode = 1;
