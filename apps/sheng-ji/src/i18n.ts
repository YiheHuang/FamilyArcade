const DICT: Record<Lang, Record<Key, string>> = { en: EN, zh: ZH };

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('familyarcade.lang');
    if (saved === 'en' || saved === 'zh') return saved;
  } catch {
    /* ignore */
  }
  if (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('zh')) {
    return 'zh';
  }
  return 'en';
}

export function t(
  lang: Lang,
  key: Key,
  params?: Record<string, string | number>,
): string {
  let text = DICT[lang][key] ?? EN[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function suitName(lang: Lang, suit: 'S' | 'H' | 'D' | 'C' | 'J'): string {
  if (suit === 'J') return lang === 'zh' ? '王' : 'joker';
  const keys = {
    S: 'suitSpades',
    H: 'suitHearts',
    D: 'suitDiamonds',
    C: 'suitClubs',
  } as const;
  return t(lang, keys[suit]);
}

export function rankName(lang: Lang, rank: string): string {
  if (rank === 'BJ') return t(lang, 'jokerBig');
  if (rank === 'SJ') return t(lang, 'jokerSmall');
  return rank;
}

export function cardName(
  lang: Lang,
  card: { suit: 'S' | 'H' | 'D' | 'C' | 'J'; rank: string },
): string {
  if (card.suit === 'J') return rankName(lang, card.rank);
  return t(lang, 'cardLabel', {
    rank: rankName(lang, card.rank),
    suit: suitName(lang, card.suit),
  });
}

