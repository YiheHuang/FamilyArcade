import { describe, it } from 'vitest';
import { mkdirSync, writeFileSync } from 'node:fs';
import { apply, legalMoves, result, setup, viewFor } from '../src/game/engine';
import { chooseMove } from '../src/ai/ai';
import { mulberry32 } from '../src/game/rng';
import type { AiLevel, GameConfig } from '../src/game/types';

interface Pair {
  a: AiLevel;
  b: AiLevel;
  label: string;
}

const GAMES_PER_PAIR = 200;
const BUDGET_MS = 40;

const PAIRS: Pair[] = [
  { a: 'companion', b: 'easy', label: 'Companion vs Easy' },
  { a: 'easy', b: 'normal', label: 'Easy vs Normal' },
  { a: 'normal', b: 'hard', label: 'Normal vs Hard' },
];

function playPair(pair: Pair, seed: string): 0 | 1 | null {
  const config: GameConfig = {
    playerCount: 2,
    seats: [
      { name: 'A', kind: 'ai', level: pair.a },
      { name: 'B', kind: 'ai', level: pair.b },
    ],
    seed,
  };
  let state = setup(config);
  let guard = 0;
  while (state.status === 'playing' && guard++ < 120) {
    const level = state.current === 0 ? pair.a : pair.b;
    const move = chooseMove(viewFor(state), state.current, {
      level,
      budgetMs: BUDGET_MS,
      rng: mulberry32(guard * 104729 + state.moves.length),
    });
    const chosen = move ?? legalMoves(state, state.current)[0];
    if (!chosen) break;
    const out = apply(state, chosen);
    if (!out.ok) break;
    state = out.state;
  }
  const res = result(state);
  if (!res || res.tiedWinners.length !== 1) return null;
  return res.tiedWinners[0] as 0 | 1;
}

describe('AI calibration', () => {
  it('writes a 200-game self-play table', () => {
    const lines = [
      '# AI calibration — 200 games per pairing',
      '',
      `> Generated by \`npm run calibrate\` with ${GAMES_PER_PAIR} seeded games per pairing, 2 players, ${BUDGET_MS} ms per move.`,
      '> A 40 ms budget keeps the table reproducible on a laptop; it is not the 850 ms Hard budget used in the app.',
      '',
      '| Pairing | Games | A wins | B wins | Draws | A win rate |',
      '| --- | ---: | ---: | ---: | ---: | ---: |',
    ];
    for (const pair of PAIRS) {
      let aWins = 0;
      let bWins = 0;
      let draws = 0;
      for (let i = 0; i < GAMES_PER_PAIR; i++) {
        const winner = playPair(pair, `calib-${pair.a}-${pair.b}-${i}`);
        if (winner === 0) aWins++;
        else if (winner === 1) bWins++;
        else draws++;
      }
      const decided = aWins + bWins;
      const rate = decided > 0 ? ((aWins / decided) * 100).toFixed(0) : '—';
      lines.push(
        `| ${pair.label} | ${GAMES_PER_PAIR} | ${aWins} | ${bWins} | ${draws} | ${rate}% |`,
      );
    }
    lines.push(
      '',
      'Interpretation: Companion is deliberately gentle; Easy should lose to Normal more often than not.',
      'Normal vs Hard is expected to be the closest pair. A 200-game binomial sample still has a',
      'standard error around 3.5 percentage points, so read the rate with that interval in mind.',
      'The table is generated, not hand-edited; rerun it on the target laptop before release.',
      '',
    );
    mkdirSync('docs', { recursive: true });
    writeFileSync('docs/ai-calibration.md', lines.join('\n'), 'utf8');
  }, 900_000);
});
