const DICTS: Record<Lang, Record<MessageKey, string>> = { zh: ZH, en: EN };

const STORAGE_KEY = 'blokus.lang';

let mode: LangMode = 'auto';

/** read the persisted override; call once at startup */
export function initI18n(): void {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v === 'zh' || v === 'en') mode = v;
  } catch {
    /* private mode */
  }
}

function systemLang(): Lang {
  const l = (typeof navigator !== 'undefined' ? navigator.language : 'en') ?? 'en';
  return l.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function langMode(): LangMode {
  return mode;
}

export function currentLang(): Lang {
  return mode === 'auto' ? systemLang() : mode;
}

/** cycle: auto -> zh -> en -> auto, persisting the choice */
export function cycleLangMode(): LangMode {
  mode = mode === 'auto' ? 'zh' : mode === 'zh' ? 'en' : 'auto';
  try {
    if (mode === 'auto') localStorage.removeItem(STORAGE_KEY);
    else localStorage.setItem(STORAGE_KEY, mode);
  } catch {
    /* ignore */
  }
  return mode;
}

/** translate; `{name}` placeholders are replaced from `params` */
export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const dict = DICTS[currentLang()];
  let text = dict[key] ?? ZH[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}

export function playerName(n: number): string {
  return t('setup.playerName', { n });
}

export function difficultyLabel(level: 'easy' | 'normal' | 'hard'): string {
  return t(`difficulty.${level}` as MessageKey);
}
