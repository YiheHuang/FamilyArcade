const DICT: Record<Lang, Record<MessageKey, string>> = { en: EN, zh: ZH };

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('familyarcade.lang');
    if (saved === 'en' || saved === 'zh') return saved;
  } catch {
    /* ignore */
  }
  if (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('zh')) {
    return 'zh';
  }
  return 'en';
}

export function t(
  lang: Lang,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  let text = DICT[lang][key] ?? EN[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function suitName(lang: Lang, suit: Suit): string {
  const keys: Record<Suit, MessageKey> = {
    S: 'suitSpades',
    H: 'suitHearts',
    D: 'suitDiamonds',
    C: 'suitClubs',
  };
  return t(lang, keys[suit]);
}

export function rankLabel(lang: Lang, rank: Rank): string {
  return rank === 'T' ? t(lang, 'rankTen') : rank;
}

export function cardName(lang: Lang, card: { rank: Rank; suit: Suit }): string {
  return t(lang, 'cardLabel', {
    rank: rankLabel(lang, card.rank),
    suit: suitName(lang, card.suit),
  });
}

export function handName(lang: Lang, category: HandCategory): string {
  const keys: Record<HandCategory, MessageKey> = {
    'royal-flush': 'royalFlush',
    'straight-flush': 'straightFlush',
    'four-of-a-kind': 'fourOfAKind',
    'full-house': 'fullHouse',
    flush: 'flush',
    straight: 'straight',
    'three-of-a-kind': 'threeOfAKind',
    'two-pair': 'twoPair',
    'one-pair': 'onePair',
    'high-card': 'highCard',
  };
  return t(lang, keys[category]);
}

export function streetName(lang: Lang, street: string): string {
  if (street === 'preflop') return t(lang, 'preflop');
  if (street === 'flop') return t(lang, 'flop');
  if (street === 'turn') return t(lang, 'turn');
  if (street === 'river') return t(lang, 'river');
  if (street === 'showdown') return t(lang, 'showdown');
  return t(lang, 'tableOver');
}
